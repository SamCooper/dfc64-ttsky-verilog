#!/usr/bin/env python3
"""Build README.md and docs/info.md from the fragments in docs/sections.

Templates in docs/templates contain lines of the form
    <!-- include: sections/foo.md -->
    <!-- include: sections/foo.md shift=1 -->
which are replaced by the fragment, optionally with its headings pushed down `shift` levels.

Relative image and link paths in a fragment are written relative to the fragment itself
(e.g. `![CPU](../images/cpu.png)` for docs/images/cpu.png) and are rewritten to be relative
to each generated file, so they resolve from both README.md and docs/info.md.

    python docs/build_docs.py          # regenerate
    python docs/build_docs.py --check  # exit 1 if the committed files are stale

Both modes also check that every uo_out pin name in info.yaml appears in docs/sections/pinout.md,
and that images exist and, for the datasheet, live in docs/ within Tiny Tapeout's size limits.
"""
import os
import re
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent
ROOT = DOCS.parent
DATASHEET = DOCS / "info.md"
TARGETS = {
    ROOT / "README.md": DOCS / "templates" / "README.md.in",
    DATASHEET: DOCS / "templates" / "info.md.in",
}
HEADER = "<!-- GENERATED by docs/build_docs.py from docs/sections and docs/templates - edit those, not this file -->\n\n"
INCLUDE = re.compile(r"^<!-- include: (\S+)(?: shift=(\d+))? -->$", re.M)
UO_PIN = re.compile(r'^\s*uo\[(\d)\]:\s*"([^"\s(]+)', re.M)
# ![alt](path "title") / [text](path), and <img src="path">
MD_LINK = re.compile(r'(?P<pre>(?P<img>!?)\[[^\]]*\]\()(?P<url>[^)\s]+)(?P<post>(?:\s+"[^"]*")?\))')
HTML_IMG = re.compile(r'(?P<pre><img\b[^>]*?\bsrc=")(?P<url>[^"]+)(?P<post>")')
MAX_IMAGE_BYTES = 512 * 1024
MAX_TOTAL_IMAGE_BYTES = 1024 * 1024


def is_relative(url):
    return not re.match(r"^([a-z][a-z0-9+.-]*:|/|#)", url, re.I)


class Renderer:
    def __init__(self, target):
        self.target_dir = target.parent
        self.images = set()

    def rebase(self, url, source_dir, is_image):
        """Rewrite a path relative to source_dir so it is relative to the generated file."""
        if not is_relative(url):
            return url
        path, sep, anchor = url.partition("#")
        resolved = (source_dir / path).resolve()
        if is_image:
            self.images.add(resolved)
        return Path(os.path.relpath(resolved, self.target_dir)).as_posix() + sep + anchor

    def rebase_paths(self, text, source_dir):
        out, in_fence = [], False
        for line in text.splitlines():
            if line.lstrip().startswith("```"):
                in_fence = not in_fence
            elif not in_fence:
                line = MD_LINK.sub(lambda m: m["pre"] + self.rebase(m["url"], source_dir, bool(m["img"])) + m["post"], line)
                line = HTML_IMG.sub(lambda m: m["pre"] + self.rebase(m["url"], source_dir, True) + m["post"], line)
            out.append(line)
        return "\n".join(out)

    def include(self, match):
        fragment = DOCS / match[1]
        text = self.rebase_paths(fragment.read_text().rstrip("\n"), fragment.parent)
        return shift_headings(text, int(match[2])) if match[2] else text

    def render(self, template):
        return HEADER + INCLUDE.sub(self.include, template.read_text())


def shift_headings(text, levels):
    out, in_fence = [], False
    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        if not in_fence and line.startswith("#"):
            line = "#" * levels + line
        out.append(line)
    return "\n".join(out)


def image_problems(target, images):
    problems = [f"{target.name}: missing image {p.relative_to(ROOT) if p.is_relative_to(ROOT) else p}"
                for p in sorted(images) if not p.is_file()]
    if target == DATASHEET:
        present = [p for p in sorted(images) if p.is_file()]
        problems += [f"info.md: image {p.relative_to(ROOT)} must be inside docs/" for p in present
                     if not p.is_relative_to(DOCS)]
        problems += [f"info.md: image {p.relative_to(DOCS)} is over 512 KB" for p in present
                     if p.stat().st_size > MAX_IMAGE_BYTES]
        if sum(p.stat().st_size for p in present) > MAX_TOTAL_IMAGE_BYTES:
            problems.append("info.md: images total more than 1 MB")
    return problems


def missing_pin_names():
    """uo_out names from info.yaml (the datasheet pin table) that pinout.md never mentions."""
    pinout = (DOCS / "sections" / "pinout.md").read_text()
    pins = UO_PIN.findall((ROOT / "info.yaml").read_text())
    return [f"uo[{i}] {name}" for i, name in pins if f"`{name}`" not in pinout]


def main():
    check = "--check" in sys.argv[1:]
    stale, problems = [], []
    for target, template in TARGETS.items():
        renderer = Renderer(target)
        text = renderer.render(template)
        problems += image_problems(target, renderer.images)
        if check:
            if not target.exists() or target.read_text() != text:
                stale.append(target.relative_to(ROOT))
        else:
            target.write_text(text)
            print(f"wrote {target.relative_to(ROOT)}")
    missing = missing_pin_names()
    if missing:
        problems.append("info.yaml pin names not found in docs/sections/pinout.md: " + ", ".join(missing))
    for problem in problems:
        print(problem)
    if stale:
        print("Out of date (run: python docs/build_docs.py): " + ", ".join(map(str, stale)))
    if stale or problems:
        sys.exit(1)


if __name__ == "__main__":
    main()
